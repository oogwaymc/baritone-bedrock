#!/usr/bin/env python3
"""Embeds baritone/dist/Baritone.lua into the DLL as a byte array.

Usage: python tools/baritone/embed_script.py
(run baritone/build.sh first to assemble dist/Baritone.lua from lua/parts)
"""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = os.path.join(root, "baritone", "dist", "Baritone.lua")
out_dir = os.path.join(root, "src", "client", "feature", "module", "modules", "game", "baritone")

data = open(src, "rb").read()
lines = []
for i in range(0, len(data), 24):
    chunk = data[i:i + 24]
    lines.append("    " + ",".join(str(b) for b in chunk) + ",")

cpp = [
    "// Generated by tools/baritone/embed_script.py from baritone/dist/Baritone.lua - do not edit.",
    '#include "pch.h"',
    '#include "BaritoneScript.h"',
    "",
    "const unsigned char kBaritoneScript[] = {",
    *lines,
    "    0",
    "};",
    "const size_t kBaritoneScriptSize = %d;" % len(data),
    "",
]
with open(os.path.join(out_dir, "BaritoneScript.cpp"), "w", newline="\n") as f:
    f.write("\n".join(cpp))

hdr = """#pragma once
#include <cstddef>

// The bot script (baritone/dist/Baritone.lua), embedded at build time.
extern const unsigned char kBaritoneScript[];
extern const size_t kBaritoneScriptSize;
"""
with open(os.path.join(out_dir, "BaritoneScript.h"), "w", newline="\n") as f:
    f.write(hdr)
print("embedded %d bytes" % len(data))
